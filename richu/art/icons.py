"""16×16 icons drawn as ASCII sprites (Pyxel-style image bank in code).

Letters map to palette colours; '.' is transparent. Icons are used for
items, goods, journal pages and the images conjured by the brush.
"""
from __future__ import annotations

import pyxel

from . import palette as P

COLORS = {
    'k': P.INK, 'B': P.BLACK, 'w': P.WHITE, 'p': P.PAPER, 'r': P.VERMILION, 'R': P.LACQUER, 'x': P.RED,
    'o': P.OCHRE, 'b': P.WOOD, 'g': P.GREY, 's': P.STONE, 'j': P.JADE, 'J': P.PINE, 'M': P.MOSS, 'y': P.YELLOW,
    'Y': P.GOLD, 'l': P.LAMP, 'u': P.DARK_BLUE, 'n': P.NAVY, 'c': P.TEAL, 'm': P.MINT, 'e': P.PERIWINKLE,
    'L': P.LIGHT_BLUE, 'f': P.PEACH, 'i': P.PINK, 'P': P.PLUM, 'd': P.DUSK, 't': P.MIST, 'O': P.ORANGE,
    'z': P.PURPLE, 'q': P.ROSE,
}

ICONS: dict[str, list[str]] = {}


def icon(name: str, rows: str) -> None:
    lines = [ln for ln in rows.strip('\n').split('\n')]
    lines = [ln.strip() for ln in lines]
    if len(lines) != 16 or any(len(ln) != 16 for ln in lines):
        raise ValueError(f'icon {name} must be 16×16, got {[len(ln) for ln in lines]}')
    ICONS[name] = lines


_images: dict[str, pyxel.Image] = {}


def image(name: str) -> pyxel.Image:
    img = _images.get(name)
    if img is None:
        img = pyxel.Image(16, 16)
        img.cls(0)
        for y, row in enumerate(ICONS.get(name) or ICONS['unknown']):
            for x, ch in enumerate(row):
                if ch != '.':
                    img.pset(x, y, COLORS[ch])
        _images[name] = img
    return img


def draw(name: str, x: float, y: float, scale: float = 1.0) -> None:
    img = image(name)
    if scale == 1.0:
        pyxel.blt(x, y, img, 0, 0, 16, 16, 0)
    else:
        off = 16 * (scale - 1) / 2
        pyxel.blt(x + off, y + off, img, 0, 0, 16, 16, 0, scale=scale)


def has(name: str) -> bool:
    return name in ICONS



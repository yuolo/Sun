#!/usr/bin/env python3
"""Generates richu/content/hanzi_meta.py: structure and frequency of characters.

    python scripts/build_meta.py

Source: npm package ``hanzi`` (MIT) — cjk-decomp decompositions and Jun Da's
character frequency list. Only the 4000 most frequent characters plus every
character in the lexicon are kept.
"""
from __future__ import annotations

import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / '.font-cache'
OUT = ROOT / 'richu' / 'content' / 'hanzi_meta.py'
TOP = 4000


def fetch(name: str) -> Path:
    dest = CACHE / name.replace('/', '__')
    if (dest / 'package').exists():
        return dest / 'package'
    CACHE.mkdir(exist_ok=True)
    meta = json.load(urllib.request.urlopen(f'https://registry.npmjs.org/{name}/latest'))
    data = urllib.request.urlopen(meta['dist']['tarball']).read()
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        tar.extractall(dest, filter='data')
    return dest / 'package'


def js_text(path: Path) -> str:
    raw = path.read_text(encoding='utf-8')
    return raw[raw.index('`') + 1 : raw.rindex('`')]


# cjk-decomp layout codes → our layouts
LAYOUT = {
    'a': 'lr', 'a/m': 'lr', 'd': 'tb', 'd/m': 'tb', 'd/t': 'tb', 's': 'wrap', 'sbl': 'wrap', 'stl': 'wrap', 'str': 'wrap',
    'sb': 'wrap', 'st': 'wrap', 'sl': 'wrap', 'sr': 'wrap', 'w': 'wrap', 'r3tr': 'repeat', 'r3gw': 'repeat', 'rrefl': 'other',
}


def main() -> int:
    pkg = fetch('hanzi') / 'lib' / 'data'
    freq: dict[str, int] = {}
    for line in js_text(pkg / 'frequencyjunda.txt.js').splitlines():
        parts = line.split('\t')
        if len(parts) > 2:
            freq[parts[1]] = int(parts[0])
    decomp: dict[str, tuple[str, list[str]]] = {}
    for line in js_text(pkg / 'cjk-decomp.txt.js').splitlines():
        m = re.match(r'^(.+?):([a-z0-9/]+)\((.*)\)$', line)
        if m:
            decomp[m.group(1)] = (m.group(2), [p for p in m.group(3).split(',') if p])

    def parts_of(ch: str, depth: int = 0) -> list[str]:
        """First-level parts that are real characters (numeric ids are expanded)."""
        if ch not in decomp or depth > 3:
            return []
        out = []
        for p in decomp[ch][1]:
            if p.isdigit():
                out += parts_of(p, depth + 1) or []
            else:
                out.append(p)
        return out

    wanted = {c for c, r in freq.items() if r <= TOP}
    lex = ROOT / 'richu' / 'content' / 'lexicon.py'
    if lex.exists():
        wanted |= set(re.findall(r'[\u3400-\u9fff]', lex.read_text(encoding='utf-8')))
    rows = []
    for ch in sorted(wanted, key=lambda c: freq.get(c, 99999)):
        code, _ = decomp.get(ch, ('', []))
        layout = LAYOUT.get(code, 'other' if code else '')
        parts = ''.join(p for p in parts_of(ch) if p != ch)
        if code.startswith('r'):
            layout = 'repeat'
        rows.append(f'{ch}\t{freq.get(ch, 0)}\t{layout}\t{parts}')
    body = '\n'.join(rows)
    OUT.write_text(
        '"""Generated by scripts/build_meta.py from npm `hanzi` (MIT): frequency rank, layout, parts."""\n'
        '# fmt: off\n'
        f'DATA = """{body}"""\n'
        '# fmt: on\n\n'
        'META: dict[str, tuple[int, str, str]] = {}\n'
        'for _line in DATA.split("\\n"):\n'
        '    _c, _f, _l, _p = _line.split("\\t")\n'
        '    META[_c] = (int(_f), _l, _p)\n',
        encoding='utf-8',
    )
    print(f'{OUT.relative_to(ROOT)}: {len(rows)} characters, {OUT.stat().st_size // 1024} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main())
